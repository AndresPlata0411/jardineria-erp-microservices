CREATE SCHEMA clientes;
CREATE SCHEMA operaciones;
CREATE SCHEMA seguridad;
CREATE SCHEMA reportes;
CREATE SCHEMA auditoria;

-- ===== operaciones =====
CREATE TABLE operaciones.oficina (
  codigo_oficina   VARCHAR(10) PRIMARY KEY,
  ciudad           VARCHAR(30) NOT NULL,
  pais             VARCHAR(50) NOT NULL,
  region           VARCHAR(50),
  codigo_postal    VARCHAR(10) NOT NULL,
  telefono         VARCHAR(20) NOT NULL,
  linea_direccion1 VARCHAR(50) NOT NULL,
  linea_direccion2 VARCHAR(50)
);

CREATE TABLE operaciones.empleado (
  codigo_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre          VARCHAR(50) NOT NULL,
  apellido1       VARCHAR(50) NOT NULL,
  apellido2       VARCHAR(50),
  extension       VARCHAR(10) NOT NULL,
  email           VARCHAR(100) NOT NULL UNIQUE
                  CHECK (email ~ '^[^@[:space:]]+@[^@[:space:]]+$'),
  codigo_oficina  VARCHAR(10) NOT NULL REFERENCES operaciones.oficina,
  codigo_jefe     INTEGER REFERENCES operaciones.empleado,
  puesto          VARCHAR(50),
  activo          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE operaciones.gama_producto (
  gama              VARCHAR(50) PRIMARY KEY,
  descripcion_texto TEXT,
  descripcion_html  TEXT,
  imagen            VARCHAR(256)
);

CREATE TABLE operaciones.proveedor (
  codigo_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre           VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE operaciones.producto (
  codigo_producto   VARCHAR(15) PRIMARY KEY,
  nombre            VARCHAR(70) NOT NULL,
  gama              VARCHAR(50) NOT NULL REFERENCES operaciones.gama_producto,
  dimensiones       VARCHAR(25),
  codigo_proveedor  INTEGER REFERENCES operaciones.proveedor,
  descripcion       TEXT,
  cantidad_en_stock INTEGER NOT NULL DEFAULT 0 CHECK (cantidad_en_stock >= 0),
  stock_minimo      INTEGER NOT NULL DEFAULT 10 CHECK (stock_minimo >= 0),
  precio_venta      NUMERIC(15,2) NOT NULL CHECK (precio_venta > 0),
  precio_proveedor  NUMERIC(15,2) CHECK (precio_proveedor >= 0),
  activo            BOOLEAN NOT NULL DEFAULT TRUE,
  CONSTRAINT ck_margen CHECK (precio_proveedor IS NULL OR precio_venta >= precio_proveedor)
);

-- ===== clientes =====
CREATE TABLE clientes.cliente (
  codigo_cliente             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre_cliente             VARCHAR(50) NOT NULL,
  nombre_contacto            VARCHAR(30),
  apellido_contacto          VARCHAR(30),
  telefono                   VARCHAR(20) NOT NULL,
  fax                        VARCHAR(20),
  linea_direccion1           VARCHAR(50) NOT NULL,
  linea_direccion2           VARCHAR(50),
  ciudad                     VARCHAR(50) NOT NULL,
  region                     VARCHAR(50),
  pais                       VARCHAR(50),
  codigo_postal              VARCHAR(10),
  codigo_empleado_rep_ventas INTEGER REFERENCES operaciones.empleado,
  limite_credito             NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (limite_credito >= 0),
  activo                     BOOLEAN NOT NULL DEFAULT TRUE,
  UNIQUE (nombre_cliente, telefono)
);

-- ===== operaciones: pedidos y pagos =====
CREATE TABLE operaciones.pedido (
  codigo_pedido  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  fecha_pedido   DATE NOT NULL DEFAULT CURRENT_DATE,
  fecha_esperada DATE NOT NULL,
  fecha_entrega  DATE,
  estado         VARCHAR(15) NOT NULL DEFAULT 'Pendiente'
                 CHECK (estado IN ('Pendiente','Entregado','Rechazado')),
  comentarios    TEXT,
  codigo_cliente INTEGER NOT NULL REFERENCES clientes.cliente,
  total          NUMERIC(15,2) NOT NULL DEFAULT 0 CHECK (total >= 0),
  UNIQUE (codigo_pedido, codigo_cliente),
  CONSTRAINT ck_fechas CHECK (fecha_esperada >= fecha_pedido
                              AND (fecha_entrega IS NULL OR fecha_entrega >= fecha_pedido)),
  CONSTRAINT ck_entrega_estado CHECK ((estado = 'Entregado') = (fecha_entrega IS NOT NULL))
);

CREATE TABLE operaciones.detalle_pedido (
  codigo_pedido   INTEGER NOT NULL REFERENCES operaciones.pedido,
  codigo_producto VARCHAR(15) NOT NULL REFERENCES operaciones.producto,
  cantidad        INTEGER NOT NULL CHECK (cantidad > 0),
  precio_unidad   NUMERIC(15,2) NOT NULL CHECK (precio_unidad > 0),
  numero_linea    SMALLINT NOT NULL CHECK (numero_linea > 0),
  PRIMARY KEY (codigo_pedido, codigo_producto),
  UNIQUE (codigo_pedido, numero_linea)
);

CREATE TABLE operaciones.pago (
  codigo_cliente INTEGER NOT NULL REFERENCES clientes.cliente,
  id_transaccion VARCHAR(50) NOT NULL,
  codigo_pedido  INTEGER,          -- NULL = pago histórico sin pedido asignado
  forma_pago     VARCHAR(40) NOT NULL
                 CHECK (forma_pago IN ('PayPal','Transferencia','Cheque','Tarjeta','Efectivo')),
  fecha_pago     DATE NOT NULL DEFAULT CURRENT_DATE,
  total          NUMERIC(15,2) NOT NULL CHECK (total > 0),
  PRIMARY KEY (codigo_cliente, id_transaccion),
  CONSTRAINT fk_pago_pedido FOREIGN KEY (codigo_pedido, codigo_cliente)
    REFERENCES operaciones.pedido (codigo_pedido, codigo_cliente)
);

-- ===== seguridad y auditoría =====
CREATE TABLE seguridad.usuario (
  id              INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  usuario         VARCHAR(50) NOT NULL UNIQUE,
  password_hash   TEXT NOT NULL,
  rol             VARCHAR(20) NOT NULL CHECK (rol IN ('admin','empleado')),
  codigo_empleado INTEGER UNIQUE REFERENCES operaciones.empleado,
  activo          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE auditoria.log (
  id          BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  esquema     TEXT NOT NULL,
  tabla       TEXT NOT NULL,
  operacion   TEXT NOT NULL CHECK (operacion IN ('INSERT','UPDATE','DELETE')),
  usuario_app TEXT NOT NULL,
  usuario_bd  TEXT NOT NULL,
  fecha       TIMESTAMPTZ NOT NULL DEFAULT now(),
  datos_old   JSONB,
  datos_new   JSONB
);

-- ===== índices (las PK y UNIQUE ya tienen el suyo) =====
CREATE INDEX ix_empleado_oficina  ON operaciones.empleado(codigo_oficina);
CREATE INDEX ix_empleado_jefe     ON operaciones.empleado(codigo_jefe);
CREATE INDEX ix_producto_gama     ON operaciones.producto(gama);
CREATE INDEX ix_producto_prov     ON operaciones.producto(codigo_proveedor);
CREATE INDEX ix_cliente_rep       ON clientes.cliente(codigo_empleado_rep_ventas);
CREATE INDEX ix_pedido_cliente    ON operaciones.pedido(codigo_cliente);
CREATE INDEX ix_pedido_estado     ON operaciones.pedido(estado);
CREATE INDEX ix_pedido_fecha      ON operaciones.pedido(fecha_pedido);
CREATE INDEX ix_detalle_producto  ON operaciones.detalle_pedido(codigo_producto);
CREATE INDEX ix_pago_pedido       ON operaciones.pago(codigo_pedido);
CREATE INDEX ix_log_fecha         ON auditoria.log(fecha);
CREATE INDEX ix_log_tabla         ON auditoria.log(tabla, operacion);
